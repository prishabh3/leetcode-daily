import { LeetCodeAccountStats } from '../types/settings';

export interface ProgressStats {
  totalTracked: number;
  totalSubmissions: number;
  easyCount: number;
  mediumCount: number;
  hardCount: number;
  languagesCount: Record<string, number>;
  reviewsCompleted: number;
}

/**
 * Generates a clean, deterministic SVG progress card
 */
export function generateProgressSvg(stats: ProgressStats): string {
  const { totalTracked, easyCount, mediumCount, hardCount } = stats;

  const total = Math.max(1, totalTracked);
  const easyPct = Math.round((easyCount / total) * 100);
  const medPct = Math.round((mediumCount / total) * 100);
  const hardPct = Math.round((hardCount / total) * 100);

  // SVG Bar widths (max 380px)
  const barWidth = 380;
  const easyW = Math.round((easyCount / total) * barWidth);
  const medW = Math.round((mediumCount / total) * barWidth);
  const hardW = Math.round((hardCount / total) * barWidth);

  return `<svg width="450" height="200" viewBox="0 0 450 200" fill="none" xmlns="http://www.w3.org/2000/svg">
  <rect width="450" height="200" rx="10" fill="#0d1117" stroke="#30363d" stroke-width="1"/>
  
  <!-- Header -->
  <text x="24" y="36" fill="#f0f6fc" font-family="-apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif" font-size="16" font-weight="600">LC-Sync Progress Tracker</text>
  <text x="426" y="36" text-anchor="end" fill="#8b949e" font-family="-apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif" font-size="12">Tracked: ${totalTracked}</text>
  
  <!-- Stacked Progress Bar -->
  <g transform="translate(24, 55)">
    <rect width="${barWidth}" height="10" rx="5" fill="#21262d" />
    <rect x="0" y="0" width="${easyW}" height="10" rx="5" fill="#238636" />
    <rect x="${easyW}" y="0" width="${medW}" height="10" fill="#d29922" />
    <rect x="${easyW + medW}" y="0" width="${hardW}" height="10" rx="5" fill="#da3633" />
  </g>
  
  <!-- Statistics Table -->
  <g transform="translate(24, 90)" font-family="-apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif">
    <!-- Easy -->
    <circle cx="6" cy="6" r="5" fill="#238636" />
    <text x="20" y="10" fill="#c9d1d9" font-size="13">Easy</text>
    <text x="100" y="10" fill="#f0f6fc" font-size="13" font-weight="600">${easyCount}</text>
    <text x="130" y="10" fill="#8b949e" font-size="12">(${easyPct}%)</text>
    
    <!-- Medium -->
    <circle cx="6" cy="36" r="5" fill="#d29922" />
    <text x="20" y="40" fill="#c9d1d9" font-size="13">Medium</text>
    <text x="100" y="40" fill="#f0f6fc" font-size="13" font-weight="600">${mediumCount}</text>
    <text x="130" y="40" fill="#8b949e" font-size="12">(${medPct}%)</text>
    
    <!-- Hard -->
    <circle cx="6" cy="66" r="5" fill="#da3633" />
    <text x="20" y="70" fill="#c9d1d9" font-size="13">Hard</text>
    <text x="100" y="70" fill="#f0f6fc" font-size="13" font-weight="600">${hardCount}</text>
    <text x="130" y="70" fill="#8b949e" font-size="12">(${hardPct}%)</text>
    
    <!-- Summary Divider & Stats -->
    <line x1="220" y1="0" x2="220" y2="76" stroke="#30363d" stroke-width="1" />
    
    <text x="240" y="20" fill="#8b949e" font-size="12">Total Solutions</text>
    <text x="240" y="40" fill="#58a6ff" font-size="18" font-weight="600">${stats.totalSubmissions}</text>
    
    <text x="340" y="20" fill="#8b949e" font-size="12">Reviews Completed</text>
    <text x="340" y="40" fill="#3fb950" font-size="18" font-weight="600">${stats.reviewsCompleted}</text>
  </g>
  
  <!-- Footer Note -->
  <text x="24" y="185" fill="#6e7681" font-family="-apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif" font-size="10">Autogenerated by LC-Sync • Personal DSA Archive</text>
</svg>`;
}

