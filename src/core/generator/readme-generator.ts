import { SyncIndex } from '../types/sync-index';
import { normalizeLanguage, getLanguageConfig, getFileExtension } from '../utils/languages';
import { formatProblemId, getProblemDirectory } from '../sync/path-sanitizer';
import { LeetCodeAccountStats } from '../types/settings';
import {
  extractLeetCodeUsername,
  getLeetCodeProfileUrl,
  getLeetCodeStatsCardUrl,
  getLeetCodeHeatmapUrl,
} from '../leetcode/profile-validator';

export const LC_SYNC_START_MARKER = '<!-- lc-sync:start -->';
export const LC_SYNC_END_MARKER = '<!-- lc-sync:end -->';

export interface ReadmeOptions {
  githubUsername?: string;
  leetcodeUsername?: string;
  leetcodeSite?: 'us' | 'cn';
  leetcodeVerified?: boolean;
  leetcodeAccountStats?: LeetCodeAccountStats;
  repoName?: string;
  basePrefix?: string; // Default: 'solutions'
  cacheBuster?: string | number;
}

/**
 * Builds the dynamic content block between the sync markers
 */
export function buildAutogeneratedSection(syncIndex: SyncIndex, options: ReadmeOptions = {}): string {
  const basePrefix = options.basePrefix || 'solutions';
  const cleanLeetCodeUser = extractLeetCodeUsername(options.leetcodeUsername);
  const cacheBuster = options.cacheBuster || Math.floor(Date.now() / 1000);

  const problemsList = Object.values(syncIndex.problems || {}).sort((a, b) => {
    const numA = parseInt(a.id, 10);
    const numB = parseInt(b.id, 10);
    if (!isNaN(numA) && !isNaN(numB)) {
      return numA - numB;
    }
    return a.id.localeCompare(b.id);
  });

  // Calculate difficulty stats
  let easy = 0;
  let medium = 0;
  let hard = 0;
  const langCounts: Record<string, number> = {};
  const topicCounts: Record<string, number> = {};

  for (const p of problemsList) {
    if (p.difficulty === 'Easy') easy++;
    else if (p.difficulty === 'Medium') medium++;
    else if (p.difficulty === 'Hard') hard++;

    for (const lang of p.languages || []) {
      // Aggregate by normalized language to group SQL variants together
      const normalized = normalizeLanguage(lang);
      const displayKey = normalized !== 'unknown' ? normalized : lang;
      langCounts[displayKey] = (langCounts[displayKey] || 0) + 1;
    }

    for (const tag of p.tags || []) {
      topicCounts[tag] = (topicCounts[tag] || 0) + 1;
    }
  }

  // Language summary table
  const langRows = Object.entries(langCounts)
    .sort((a, b) => b[1] - a[1])
    .map(([lang, count]) => {
      const cfg = getLanguageConfig(lang as any);
      return `| ${cfg.name} | \`${count}\` |`;
    })
    .join('\n');

  // Topics list (top 15)
  const topTopics = Object.entries(topicCounts)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 15)
    .map(([topic, count]) => `\`${topic} (${count})\``)
    .join(' • ');

  // Full problem table rows
  const problemRows = problemsList.map((p) => {
    const paddedId = formatProblemId(p.id);
    const dir = getProblemDirectory(p.id, p.slug);
    const dirLink = `[${p.title}](./${basePrefix}/${dir})`;
    const notesLink = `[Notes](./${basePrefix}/${dir}/notes.md)`;
    const langs = (p.languages || [])
      .map((l) => `[\`${getLanguageConfig(l as any).name}\`](./${basePrefix}/${dir}/${l})`)
      .join(', ');
    const tags = (p.tags || []).slice(0, 3).join(', ') || '-';
    const nextReview = p.nextReviewDate ? `\`${p.nextReviewDate}\`` : '-';
    const lastSynced = p.lastSyncedAt ? p.lastSyncedAt.split('T')[0] : '-';

    return `| ${paddedId} | ${dirLink} | ${p.difficulty} | ${langs} | ${tags} | ${notesLink} | ${lastSynced} | ${nextReview} |`;
  });

  // Recently synchronized problems (top 8 sorted by lastSyncedAt descending)
  const recentProblems = [...problemsList]
    .sort((a, b) => new Date(b.lastSyncedAt || 0).getTime() - new Date(a.lastSyncedAt || 0).getTime())
    .slice(0, 8);

  const recentTableRows = recentProblems.map((p) => {
    const paddedId = formatProblemId(p.id);
    const dir = getProblemDirectory(p.id, p.slug);
    const primaryLang = p.languages?.[0] || 'cpp';
    const ext = getFileExtension(primaryLang as any);
    const problemLink = `[${paddedId}. ${p.title}](./${basePrefix}/${dir})`;
    const langBadge = (p.languages || []).map((l) => getLanguageConfig(l as any).name).join(', ') || 'C++';
    const solutionLink = `[solution.${ext}](./${basePrefix}/${dir}/${primaryLang}/solution.${ext})`;

    return `| ${problemLink} | ${p.difficulty} | ${langBadge} | ${solutionLink} |`;
  });

  // Header badges
  const badges: string[] = [
    `[![Problems Tracked](https://img.shields.io/badge/Problems%20Tracked-${problemsList.length}-blue)]()`,
  ];

  const site = options.leetcodeSite || 'us';

  if (cleanLeetCodeUser) {
    badges.push(
      `[![LeetCode](https://img.shields.io/badge/LeetCode-Profile-orange?logo=leetcode)](${getLeetCodeProfileUrl(cleanLeetCodeUser, site)})`
    );
  }

  if (options.githubUsername) {
    badges.push(
      `[![GitHub](https://img.shields.io/badge/GitHub-Profile-181717?logo=github)](https://github.com/${options.githubUsername})`
    );
  }

  // LeetCode Account section
  let profileSection = '';
  if (cleanLeetCodeUser) {
    const profileUrl = getLeetCodeProfileUrl(cleanLeetCodeUser, site);

    // Only embed external stats cards if verified and NOT explicitly marked unverified/invalid
    if (options.leetcodeVerified !== false) {
      const statsUrl = getLeetCodeStatsCardUrl(cleanLeetCodeUser, site, cacheBuster);
      const heatmapUrl = getLeetCodeHeatmapUrl(cleanLeetCodeUser, site, cacheBuster);

      let statsSummary = '';
      if (options.leetcodeAccountStats) {
        const s = options.leetcodeAccountStats;
        const rankText = s.ranking ? ` • Ranking: \`#${s.ranking}\`` : '';
        statsSummary = `
- **Total Solved on LeetCode**: **${s.totalSolved}** (🟢 Easy: **${s.easySolved}** • 🟡 Medium: **${s.mediumSolved}** • 🔴 Hard: **${s.hardSolved}**)${rankText}
`.trim();
      }

      profileSection = `
## 🌐 LeetCode Account

### 🔗 LeetCode Profile
[${cleanLeetCodeUser}](${profileUrl})
${statsSummary ? `\n${statsSummary}\n` : ''}
### 📈 Account Statistics
[![LeetCode Stats](${statsUrl})](${profileUrl})

### 🔥 Submission Activity Heatmap
[![LeetCode Heatmap](${heatmapUrl})](${profileUrl})

_External card caching notice: JacobLinCool and GitHub Camo cache card graphics for 1–4 hours. Local repository records below are updated immediately upon every sync._
`.trim();
    } else {
      // If unverified or invalid username, do not embed broken cards with mock stats!
      profileSection = `
## 🌐 LeetCode Account

### 🔗 LeetCode Profile
[${cleanLeetCodeUser}](${profileUrl})

_External LeetCode statistics cards are unverified. Connect your active LeetCode session or verify your account in LC-Sync Settings._
`.trim();
    }
  } else {
    profileSection = `
## 🌐 LeetCode Account

### 🔗 LeetCode Profile
[LeetCode](https://leetcode.com) — _Connect your active LeetCode session in LC-Sync Settings to view live account statistics and activity heatmap._
`.trim();
  }

  const githubLink = options.githubUsername && options.repoName
    ? ` • [GitHub Solutions Repo](https://github.com/${options.githubUsername}/${options.repoName})`
    : '';

  return `
${profileSection}

## 📊 LC-Sync Repository

<p align="center">
  <img src="./assets/progress.svg" alt="LC-Sync Progress" width="450" />
</p>

${badges.join(' ')}

- **Distinct Problems Tracked**: **${problemsList.length}**
- **Total Accepted Submissions**: **${syncIndex.totalSubmissions}**
- **Repository Solutions & Historical Versions**: **${syncIndex.totalSubmissions}**${githubLink}

### 🎯 Difficulty Breakdown
| Difficulty | Solved |
| :--- | :--- |
| 🟢 Easy | **${easy}** |
| 🟡 Medium | **${medium}** |
| 🔴 Hard | **${hard}** |

### 💻 Language Distribution
| Language | Solved Problems |
| :--- | :--- |
${langRows || '| None | 0 |'}

### 🏷️ Topic Tags
${topTopics || '_No topic tags recorded yet._'}

---

## 📚 Solution Directory

👉 **[Browse All Solutions → ${basePrefix}/](./${basePrefix}/)**

### Recently Synchronized Problems

| Problem | Difficulty | Language | Solution |
| :--- | :-: | :--- | :--- |
${recentTableRows.length > 0 ? recentTableRows.join('\n') : '| No solutions synchronized yet | - | - | - |'}

<details>
<summary><strong>View All Tracked Problems (${problemsList.length})</strong></summary>

| # | Title | Difficulty | Languages | Topics | Notes | Date Solved | Next Revision |
| :-: | :--- | :-: | :--- | :--- | :-: | :-: | :-: |
${problemRows.length > 0 ? problemRows.join('\n') : '| - | No problems tracked yet | - | - | - | - | - | - |'}

</details>

---

_Last synchronized via LC-Sync: \`${syncIndex.lastUpdated || new Date().toISOString()}\`_
`;
}

/**
 * Generates full README, preserving any manual content outside marker tags
 */
export function generateReadme(
  existingReadmeContent: string | null,
  syncIndex: SyncIndex,
  options: ReadmeOptions = {}
): string {
  const basePrefix = options.basePrefix || 'solutions';
  const autoSection = buildAutogeneratedSection(syncIndex, options);

  const defaultHeader = `# ⚡ LeetCode Daily

> My LeetCode problem-solving journey — automatically synchronized to GitHub using LC-Sync.
`;

  const defaultFooter = `
### 📂 Repository Layout

\`\`\`text
├── README.md                # Progress summary & solution index
├── ${basePrefix}/               # All problem solutions by question number & title
│   └── 0013-roman-to-integer/
│       ├── cpp/
│       │   └── solution.cpp # Source code by language
│       ├── metadata.json    # Problem metadata and revision schedule
│       └── notes.md         # Learning journal & approach notes
├── data/
│   └── sync-index.json      # Durable sync index and deduplication records
└── assets/
    └── progress.svg         # Locally generated SVG progress summary
\`\`\`

_Automatically synchronized using [LC-Sync](https://github.com/prishabh3/leetcode-daily)._
`;

  if (!existingReadmeContent || !existingReadmeContent.includes(LC_SYNC_START_MARKER)) {
    // Brand new README or no markers present
    return `${defaultHeader}
${LC_SYNC_START_MARKER}
${autoSection.trim()}
${LC_SYNC_END_MARKER}
${defaultFooter}`.trim() + '\n';
  }

  // Preserve manual user content before start marker and after end marker
  const startIndex = existingReadmeContent.indexOf(LC_SYNC_START_MARKER);
  const endIndex = existingReadmeContent.indexOf(LC_SYNC_END_MARKER);

  if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
    // Malformed markers: append cleanly
    return `${existingReadmeContent}\n\n${LC_SYNC_START_MARKER}\n${autoSection.trim()}\n${LC_SYNC_END_MARKER}\n`;
  }

  let prefix = existingReadmeContent.slice(0, startIndex);
  const suffix = existingReadmeContent.slice(endIndex + LC_SYNC_END_MARKER.length);

  // Clean up any legacy stats cards or headers placed in prefix before markers
  prefix = prefix.replace(/##\s*📈?\s*LeetCode Stats[\s\S]*?(?=(?:##\s|<!--\s*lc-sync|$))/gi, '');
  prefix = prefix.replace(/##\s*📅?\s*Submission Activity[\s\S]*?(?=(?:##\s|<!--\s*lc-sync|$))/gi, '');
  prefix = prefix.replace(/\[!\[LeetCode.*?\]\(https:\/\/leetcard\.jacoblin\.cool\/.*?\)\]\(.*?\)\s*/gi, '');
  prefix = prefix.trimEnd() + '\n\n';

  return `${prefix}${LC_SYNC_START_MARKER}
${autoSection.trim()}
${LC_SYNC_END_MARKER}${suffix}`;
}
